// 생체 수신 나이 산출 — 연결끊김 판정의 기준 시각을 정한다(행 도착이 아니라 심박 측정 기준).
//
// ★ 행 ts 로 재면 안 된다(2026-08-15 실측). 워치를 벗어도 워크아웃 세션이 활동에너지를 계속
// 누적해 **5초마다 행이 들어온다** — 미착용 구간에도 12건/분이 그대로 왔다. 그래서 행 ts 기준
// 신선도는 영원히 통과한다.
//
// ⚠ 이 수정이 고치는 것은 "정상으로 잘못 세는 것"이 **아니다**. 심박이 null 이면
// `heartRateStatus` 가 idle 을 돌려주고 `overallStatus` 도 idle 이라 집계는 이미 "대기"로 센다
// (08-12 신호등 false-OK 수정이 그대로 작동). "정상" 으로 세던 것은 **워치가 마지막 값을 무한
// 복사하던 시절**의 이야기이고 그쪽은 heartbeatMaxAge 로 이미 막았다.
// 여기서 바로잡는 것은 셋이다 —
//   ① **"대기"와 "연결끊김"의 구분.** 받은 적 없는 것(출근 전)과 받다가 끊긴 것은 관리자에게
//      전혀 다른 신호다. 행 ts 가 계속 갱신되면 후자가 전자로 보인다.
//   ② **신호 막대(signalLevel).** 행 ts 기준이라 생체가 끊겨도 4칸 꽉 찬 "수신 양호"로 보였다.
//   ③ **잔여 sticky 생체값.** stale 이 아니면 `gateStaleVitals` 가 안 걸려 SpO₂·체온의 직전값이
//      현재값처럼 남는다.
//
// 왜 심박 하나로 생체 전체를 판정하는가 — 최근 24시간 실측에서 **연속으로 오는 생체 신호는
// 심박뿐**이다(심박 99.3% · SpO₂ 4건 · 손목온도·HRV·안정심박·보행심박·호흡수 전부 0건).
// SpO₂ 는 같은 광학(PPG) 센서라 손목이 떨어지면 함께 멈추고, 심부체온 추정과 PSI 는 **심박을
// 입력으로 쓴다**. 즉 심박이 끊긴 시점에 독립적으로 살아 있는 생체 신호는 하나도 없다.
// 활동에너지·걸음은 생체가 아니라 움직임 누적이고 **사람이 없어도 나온다**.
// ⚠⚠ 이것이 잡는 것은 "미착용" 이 아니라 **"심박 측정이 멈춘 상태"** 다.
//
// 2026-08-15 20:00 실측 — 워치를 **벗은 채로** 70분간 심박 68~78 이 계속 생성됐다
// (891행 · 고유값 11개 · 값이 계속 변동 · 평균 지연 1.78초 = 복사가 아니라 실측).
// 대조로 같은 날 어제 굳음 구간은 8,771행에 고유값 2개 · 평균 지연 15.8초였다(그쪽이 복사).
// 상시 `HKWorkoutSession` 이 광학센서를 켜 둔 채 손목 감지를 우회하므로 **벗어도 측정이 이어질
// 수 있고, 그때는 이 게이트가 발동하지 않는다** — 화면에는 "착용 중·정상" 으로 보인다.
// 값이 그럴듯하게 흔들리므로 값이 고정되던 복사 결함보다 알아채기 어렵다.
//
// 즉 이 장치의 효능 범위는 "측정이 멈추는 형태의 중단"(전원·앱 종료·센서 실패·거리 이탈 등)이다.
// 착용 여부 판정은 별개 문제이고 심박만으로는 불가능하다 — 후보 신호는 가속도·걸음(현재 앱이
// 안 보내 DB 전부 NULL)이나 **자는 사람도 같은 모양**이라 단독으로는 못 쓴다. 설계 필요.
export type VitalAgeSample = {
  ts: string;
  heartRateMeasuredAt?: string;
};

/**
 * 생체 수신 나이(ms). 심박 측정 시각이 있으면 그것을, 없으면 행 ts 를 기준으로 잰다.
 *
 * 측정 시각이 없는 샘플(구 앱·이벤트 전용 행)은 종전 동작 그대로 행 ts 폴백 — 하위 호환.
 * 파싱 불가한 값도 같은 폴백을 탄다(NaN 이 비교를 통과해 "항상 신선"이 되는 것을 막는다).
 */
export function vitalAgeMs(sample: VitalAgeSample, nowMs: number): number {
  const rowMs = new Date(sample.ts).getTime();
  const hrAt = sample.heartRateMeasuredAt;
  if (hrAt !== undefined) {
    const hrMs = new Date(hrAt).getTime();
    if (Number.isFinite(hrMs)) return nowMs - hrMs;
  }
  return nowMs - rowMs;
}

// ── 연결끊김 문턱 — 기기마다 전송 주기가 다르므로 문턱도 갈라야 한다 ─────────────
//
// ★ 문턱은 취향이 아니라 **전송 주기의 함수**다. 워치가 T초마다 올리면 심박 나이는 0→T 를
// 왕복하므로, 문턱이 T 이하면 매 주기 끝자락마다 "연결끊김"이 뜬다(정상인데 오탐).
//
// 애플(watchOS) = 30초 배칭 → 60초 문턱. 종전 값 그대로다.
// 갤럭시(Wear OS) = **120초** 배칭 → 150초 문턱.
//   120초는 발열 조치의 산물이다(2026-08-25 `7ef6ca9`). 기기 발열이 피부온을 오염시키는 것이
//   실측으로 확정돼(4분 미착용 후 재착용 10분에 피부온 +2.33℃ · **주변온 +2.51℃** — 주변온이
//   더 오른 것이 결정적) LTE 기상을 절반으로 줄였다. 갤럭시를 도입한 이유가 실측 피부온이므로
//   **주기를 다시 줄여 문턱을 맞추는 것은 목적을 훼손한다.** 문턱 쪽이 따라간다.
//
// ⚠ 이 값을 줄이려면 워치 주기부터 확인한다 — 가드가 `CollectorService.FLUSH_INTERVAL_MS` 와
//   이 상수를 직접 대조한다(2026-08-25-stale-threshold-by-origin.guard.test.ts).
export const STALE_MS_DEFAULT = 60_000;
export const STALE_MS_WEAROS = 150_000;

/**
 * 출처별 연결끊김 문턱(ms). 모르는 출처·구 데이터는 종전 60초 그대로 — 하위 호환.
 */
export function staleThresholdMs(dataOrigin: string | undefined): number {
  return dataOrigin === "wearos_data_vitalguard" ? STALE_MS_WEAROS : STALE_MS_DEFAULT;
}

// ── 끊김의 두 종류 — 같은 stale 이라도 관제자가 할 일이 정반대다 ──────────────
//
// ★ **판정은 안 가른다.** 두 종류 모두 `stale` 이고 sticky 값 차단·신호 강등·톤 강등·
//   이상 집계는 전부 종전 그대로다. 가르는 것은 **관제자가 읽는 글자뿐**이다.
//   판정을 건드리면 안전 동작 다섯 곳의 회귀 위험을 지는데 얻는 것은 이름표 하나다.
//
// 실측 근거(2026-08-28 · 7일) —
//   갤럭시 심박 간격 p50 120.9s · p90 231.9s · p95 461.7s · p99 4,210s (n=650)
//   애플                p50   5.0s · p90   5.5s · p95   6.2s · p99     9.6s (n=28,318)
// 애플은 주기의 1.9배 안에서 도는데 갤럭시는 35배까지 벌어진다. 그런데 **전송은 정상이다** —
// 배치 간격 median 120.3s 로 `CollectorService.FLUSH_INTERVAL_MS` 와 일치한다.
// 즉 링크는 멀쩡한 채 심박만 묵는 구간이 상시 생긴다.
//
// ⚠ 행 수로 세지 말 것 — 08-27 ML 투입 이후 **낙상 섀도 행**이 섞인다(같은 24시간에 489건).
//   섀도는 `ts`·`fallCandidateId`·`accelMagnitudeG`·`fallTrace` 만 싣고 심박·배터리를 **설계상**
//   안 싣는다. 이걸 안 빼면 "샘플의 70%가 빈 행" 같은 틀린 수가 나온다(실제로 한 번 그렇게 셌다).
//   섀도를 뺀 생체 행은 215건 중 202건이 심박을 단다(94.0%) — 그중 13건만 심박이 없고
//   그 13건은 **전부 배터리를 싣는다**. 즉 수집 tick 은 돌았고 심박만 안 잡힌 것이다.
//   `AND fall_candidate IS NULL AND fall_update_phase IS NULL` 로 거른다.
//
// 이 둘을 같은 "연결끊김" 으로 부르면 관제자가 폰을 찾아 현장에 간다 — 정작 필요한 것은
// "워치를 고쳐 차세요" 한마디다.
//
// ⚠ 문턱을 올려 덮는 방향은 막혀 있고, 막혀 있는 것이 옳다 — 가드 상한(주기 2배)까지 올려도
//   오탐이 651건 중 104→64 로만 줄고, 그 위는 진짜 끊김을 한 주기 통째로 놓친다
//   (2026-08-25-stale-threshold-by-origin.guard.test.ts).
export type StaleKind =
  /** 샘플 자체가 안 온다 — 폰·네트워크·앱. 사람을 찾아가야 한다. */
  | "disconnected"
  /** 샘플은 오는데 심박만 묵는다 — 워치 착용·센서. 말 한마디로 끝난다. */
  | "hrSilent";

/**
 * `stale` 로 판정된 샘플이 둘 중 어느 종류인가.
 *
 * ⚠ **이 함수는 stale 여부를 판정하지 않는다** — 이미 stale 인 것의 종류만 가른다.
 *   stale 이 아닌 샘플에 부르면 결과는 무의미하다(호출부가 stale 분기 안에서만 쓴다).
 *
 * 기준 = **행 나이**. 행이 신선하다는 것은 샘플이 도착하고 있다는 뜻이고(링크 생존),
 * 그런데도 stale 이라는 것은 심박 시각만 묵었다는 뜻이다.
 * 문턱은 심박 쪽과 같은 값을 쓴다 — 갤럭시 샘플도 같은 120초 주기로 오므로 자가 같다.
 *
 * ★ **낙상 섀도 행도 도착 근거로 센다 — 의도한 것이다.**(2026-08-28 · 옆 세션 지적으로 검토)
 *   섀도는 생체를 안 싣지만 워치의 같은 큐에 들어가 **같은 flush 로** 올라온다.
 *   그리고 워치에 **업로드 경로가 그 하나뿐**이다(전부 `CollectorService.kt` 실측) —
 *     `:77`  `queue` 객체 하나를 만들어 `:95` 수집 엔진과 `:117` `FallShadowReporter` 가 공유
 *     `:106` `HttpTransport` 생성은 여기 한 번, `pipeline` 에만 물린다
 *     `:277` `pipeline.flushOnce` 호출은 **`tick`(`:272-295`) 안 한 곳뿐**
 *   즉 섀도가 서버에 닿았다는 것은 "링크가 살아 있다" 보다 강한 **"`tick` 이 돌았다"** 이다.
 *
 *   이 사실이 반례 하나를 미리 닫는다 — *IMU 경로만 살아 있고 수집 tick 은 죽었는데 섀도가
 *   그 죽음을 가리는 경우*. **성립 불가다.** tick 이 안 돌면 flush 가 없고, flush 가 없으면
 *   섀도도 서버에 못 온다. (섀도 항목 생성은 IMU 스레드지만 전송은 아니다.)
 *
 *   여기서 묻는 것은 "생체가 오는가" 가 아니라 **"사람을 찾아가야 하는가"** 이고,
 *   tick 이 도는 기기에 사람을 보낼 이유는 없다.
 *   ⚠ 워치가 죽으면 섀도도 함께 끊기므로 `disconnected` 로 넘어간다 — 그 경로는 막히지 않는다.
 *
 *   ⚠ **아래 수를 비율 상수로 읽지 말 것.** 섀도는 주기 신호가 아니라 1.8G 게이트에 걸릴 때만
 *     나는 **산발** 신호라, 그날의 후보 발생률일 뿐이다(가드에도 안 박았다).
 *     2026-08-28 하루 관측 = 섀도 489건 중 89건이 직전 150초에 생체 행 없이 도착 → 이 판단을 탐.
 *
 * 파싱 불가한 `ts` 는 `disconnected` — 도착을 확인할 수 없으면 안전측(사람이 가 보는 쪽)으로 센다.
 */
export function staleKind(
  sample: VitalAgeSample,
  nowMs: number,
  dataOrigin: string | undefined,
): StaleKind {
  const rowMs = new Date(sample.ts).getTime();
  if (!Number.isFinite(rowMs)) return "disconnected";
  return nowMs - rowMs > staleThresholdMs(dataOrigin) ? "disconnected" : "hrSilent";
}

